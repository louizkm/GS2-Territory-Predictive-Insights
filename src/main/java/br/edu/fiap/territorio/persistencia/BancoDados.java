package br.edu.fiap.territorio.persistencia;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;

public final class BancoDados {
    private final String url;

    public BancoDados(String url) { this.url = url; }

    public Connection conectar() throws SQLException {
        return DriverManager.getConnection(url, "sa", "");
    }

    public void inicializar() throws SQLException {
        try (Connection conexao = conectar(); Statement comando = conexao.createStatement()) {
            comando.executeUpdate("""
                CREATE TABLE IF NOT EXISTS medicao (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    sensor_id VARCHAR(50) NOT NULL,
                    tipo VARCHAR(30) NOT NULL,
                    regiao VARCHAR(120) NOT NULL,
                    valor DOUBLE PRECISION NOT NULL,
                    instante TIMESTAMP NOT NULL
                )
                """);
            comando.executeUpdate("""
                CREATE TABLE IF NOT EXISTS alerta (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    sensor_id VARCHAR(50) NOT NULL,
                    tipo VARCHAR(30) NOT NULL,
                    nivel VARCHAR(20) NOT NULL,
                    valor_previsto DOUBLE PRECISION NOT NULL,
                    limite_superado DOUBLE PRECISION NOT NULL,
                    justificativa VARCHAR(1000) NOT NULL,
                    instante TIMESTAMP NOT NULL
                )
                """);
            comando.executeUpdate("CREATE INDEX IF NOT EXISTS idx_medicao_sensor_instante ON medicao(sensor_id, instante)");
            comando.executeUpdate("CREATE INDEX IF NOT EXISTS idx_alerta_instante ON alerta(instante)");
        }
    }
}
